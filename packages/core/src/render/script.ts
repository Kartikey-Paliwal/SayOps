import type { Plan, PlanCheck, PlanStep } from "../schemas";
import type { RenderContext } from "./context";
import { CHILD_HELPERS, isSecretParam, oneLine, referencedVars, shq, slugify } from "./shell";

/**
 * Renders a validated plan into a guarded bash script. Deterministic: same plan, same bytes.
 *
 * Plan commands are never inlined as code. Each one is embedded as a single-quoted string and
 * piped to a child `bash -s` (locally, or on $HOST over ssh) together with `set -euo pipefail`,
 * the parameters it uses (printf %q) and the backup/restore helpers. Whatever the model wrote
 * cannot break the structure of the script. Targets bash 3.2 (macOS) and newer.
 */
export function renderScript(plan: Plan, ctx: RenderContext): string {
  const file = `${slugify(plan.title)}.sh`;
  const names = plan.params.map((p) => p.name);
  const flagParams = plan.params.filter((p) => !isSecretParam(p.from));
  const secretParams = plan.params.filter((p) => isSecretParam(p.from));
  const flag = (name: string) => `--${name.toLowerCase().replace(/_/g, "-")}`;
  const usageLine = [`./${file}`, ...flagParams.map((p) => `${flag(p.name)} <${p.name}>`), "[--dry-run] [--yes]"].join(" ");
  const quote = (id: string) => (ctx.sources[id] ? `${id} “${oneLine(ctx.sources[id], 110)}”` : id);
  const why = (ids: string[]) => ids.map(quote).join(" · ");
  const vars = (cmd: string) => referencedVars(cmd, names).join(" ");
  const exec = (remote: boolean, cmd: string) =>
    `sayops_exec ${remote ? "remote" : "local"} ${shq(cmd)}${vars(cmd) ? ` ${vars(cmd)}` : ""}`;
  const L: string[] = [];

  // ---- header -------------------------------------------------------------
  L.push(
    "#!/usr/bin/env bash",
    `# ${oneLine(plan.title)} — generated by SayOps from session ${ctx.sessionId}, plan v${ctx.version}.`,
    "# Review every step before running it, and prove it in a sandbox before using it on real systems.",
    "# Sources: C<n> = a command you ran, N<n> = something you said, X<n> = a correction.",
    "#",
    `# Usage: ${usageLine}`,
  );
  if (secretParams.length) L.push(`# Secrets are read from the environment only: ${secretParams.map((p) => p.name).join(", ")}`);
  L.push(
    "# Exit codes: 0 done or nothing to do · 1 a step failed and the run stopped (no rollback for that step)",
    "#             2 bad parameters · 3 approval required",
    "#             4 a step failed, rollback ran, recovery NOT verified: check the system by hand",
    "#             5 a step failed, rolled back, recovery verified by the plan's checks (task not done)",
    "# Transports: SAYOPS_TRANSPORT=ssh (default) · local · docker (with SAYOPS_DOCKER_CONTAINER, for sandboxes).",
    "# SAYOPS_EVENTS=<file> appends one machine-readable line per event (used by the proof runner).",
    "#",
    "# Commands are single-quoted on purpose: they expand inside the child shell that runs them,",
    "# where their parameters are set (see sayops_exec), never in this script.",
    "# shellcheck disable=SC2016",
    "set -euo pipefail",
    "",
    `SAYOPS_RUN_ID="\${SAYOPS_RUN_ID:-$(date -u +%Y%m%dT%H%M%SZ)-$$}"`,
    `SAYOPS_TRANSPORT="\${SAYOPS_TRANSPORT:-ssh}"`,
    `SAYOPS_YES="\${SAYOPS_APPROVED:-0}"`,
    "SAYOPS_DRY_RUN=0",
    "SAYOPS_ROLLED_BACK=0",
  );
  for (const p of plan.params) L.push(`${p.name}="\${${p.name}:-}"`);

  // ---- arguments ------------------------------------------------------------
  L.push(
    "",
    "usage() {",
    `  echo ${shq(`usage: ${usageLine}`)}`,
    ...plan.params.map((p) => `  echo ${shq(`  ${p.name.padEnd(12)} ${isSecretParam(p.from) ? "(env only) " : ""}was "${p.from}" when recorded${p.why ? ` (${p.why})` : ""}`)}`),
    `  echo '  --dry-run    print every command without running anything'`,
    `  echo '  --yes        approve HIGH-risk steps (or set SAYOPS_APPROVED=1)'`,
    "}",
    "",
    'while [ "$#" -gt 0 ]; do',
    '  case "$1" in',
  );
  for (const p of flagParams) {
    L.push(`    ${flag(p.name)}) [ "$#" -ge 2 ] || { echo "sayops: $1 needs a value" >&2; exit 2; }; ${p.name}="$2"; shift 2 ;;`);
  }
  L.push(
    "    --dry-run) SAYOPS_DRY_RUN=1; shift ;;",
    "    --yes) SAYOPS_YES=1; shift ;;",
    "    -h|--help) usage; exit 0 ;;",
    '    *) echo "sayops: unknown argument: $1" >&2; usage >&2; exit 2 ;;',
    "  esac",
    "done",
    "",
    "sayops_require() {",
    '  if [ -z "$2" ]; then echo "sayops: missing required parameter $1" >&2; usage >&2; exit 2; fi',
    '  if [ -n "$3" ] && ! [[ "$2" =~ $3 ]]; then echo "sayops: $1 must match $3" >&2; exit 2; fi',
    "}",
  );
  for (const p of plan.params) L.push(`sayops_require ${p.name} "$${p.name}" ${shq(p.validate ?? "")}`);
  if (plan.remote_host) {
    L.push(`case "$${plan.remote_host}" in -*) echo "sayops: ${plan.remote_host} must not start with '-'" >&2; exit 2 ;; esac`);
  }
  L.push(
    'case "$SAYOPS_TRANSPORT" in',
    "  ssh|local) ;;",
    '  docker) [ -n "${SAYOPS_DOCKER_CONTAINER:-}" ] || { echo "sayops: SAYOPS_TRANSPORT=docker needs SAYOPS_DOCKER_CONTAINER" >&2; exit 2; } ;;',
    '  *) echo "sayops: unknown SAYOPS_TRANSPORT: $SAYOPS_TRANSPORT" >&2; exit 2 ;;',
    "esac",
  );

  // ---- runtime --------------------------------------------------------------
  L.push(
    "",
    'sayops_log() { printf \'sayops: %s\\n\' "$*"; }',
    'sayops_err() { printf \'sayops: %s\\n\' "$*" >&2; }',
    'sayops_event() { if [ -n "${SAYOPS_EVENTS:-}" ]; then printf \'%s\\n\' "$*" >> "$SAYOPS_EVENTS"; fi; }',
    "",
    "# Child shell preamble: strict mode, the parameters a command uses, and the backup helpers.",
    "sayops_preamble() {",
    "  local name",
    "  printf 'set -euo pipefail\\n'",
    "  printf 'SAYOPS_RUN_ID=%q\\nSAYOPS_SUDO=%q\\n' \"$SAYOPS_RUN_ID\" \"${SAYOPS_SUDO:-auto}\"",
    "  for name in \"$@\"; do printf 'export %s=%q\\n' \"$name\" \"${!name}\"; done",
    "  cat <<'SAYOPS_HELPERS'",
    CHILD_HELPERS,
    "SAYOPS_HELPERS",
    "}",
    "",
    "# sayops_exec <local|remote> <command> [VAR...]",
    "sayops_exec() {",
    "  local where=$1 cmd=$2",
    "  shift 2",
    '  if [ "$SAYOPS_DRY_RUN" = 1 ]; then printf \'  [dry-run] (%s) %s\\n\' "$where" "$cmd"; return 0; fi',
    "  printf '  $ %s\\n' \"$cmd\"",
    '  if [ "$SAYOPS_TRANSPORT" = docker ]; then',
    `    { sayops_preamble "$@"; printf '%s\\n' "$cmd"; } | docker exec -i "$SAYOPS_DOCKER_CONTAINER" bash -s`,
    ...(plan.remote_host
      ? [`  elif [ "$where" = remote ] && [ "$SAYOPS_TRANSPORT" = ssh ]; then`, `    { sayops_preamble "$@"; printf '%s\\n' "$cmd"; } | ssh -o BatchMode=yes -- "$${plan.remote_host}" bash -s`]
      : []),
    "  else",
    `    { sayops_preamble "$@"; printf '%s\\n' "$cmd"; } | bash -s`,
    "  fi",
    "}",
    "",
    "# Conditions are never treated as met in a dry run, so the whole plan is shown.",
    'sayops_check() { if [ "$SAYOPS_DRY_RUN" = 1 ]; then sayops_exec "$@"; return 1; fi; sayops_exec "$@"; }',
    "",
    "sayops_confirm() {",
    '  if [ "$SAYOPS_YES" = 1 ] || [ "$SAYOPS_DRY_RUN" = 1 ]; then return 0; fi',
    "  if [ -t 0 ]; then",
    '    local answer=""',
    '    printf \'sayops: %s is HIGH risk: %s\\nType YES to run it: \' "$1" "$2"',
    '    read -r answer || true',
    '    [ "$answer" = YES ] && return 0',
    "  fi",
    '  sayops_err "$1 is HIGH risk and was not approved (use --yes or SAYOPS_APPROVED=1)"',
    "  exit 3",
    "}",
    "",
  );

  // ---- rollback and verified recovery ----------------------------------------
  // A failed run is only reported as recovered when the plan's own checks pass afterwards.
  L.push("SAYOPS_ROLLBACK_OK=0", "sayops_rollback() {", '  [ "$SAYOPS_ROLLED_BACK" = 1 ] && return 0', "  SAYOPS_ROLLED_BACK=1", "  sayops_event rollback_start");
  if (plan.rollback.length) {
    L.push("  local ok=1", '  sayops_err "rolling back"');
    plan.rollback.forEach((r, i) => {
      L.push(`  # rollback ${i + 1} — ${why([r.why])}`);
      L.push(`  if ${exec(r.remote, r.run)}; then sayops_event rollback_cmd ${i + 1} ok; else ok=0; sayops_event rollback_cmd ${i + 1} fail; sayops_err ${shq(`rollback ${i + 1} failed: ${oneLine(r.run, 80)}`)}; fi`);
    });
    L.push(
      '  SAYOPS_ROLLBACK_OK=$ok',
      '  if [ "$ok" = 1 ]; then sayops_err "rollback commands finished"; else sayops_err "ROLLBACK INCOMPLETE"; fi',
    );
  } else {
    L.push('  sayops_err "no rollback was defined for this task"');
  }
  L.push("}", "");
  L.push("# Runs the plan's verification checks against the rolled-back system.", "sayops_verify_recovery() {");
  if (plan.verify.length) {
    plan.verify.forEach((v, i) => {
      L.push(`  if ${exec(v.remote, v.run)}; then sayops_event recovery_check ${i + 1} ok; else sayops_event recovery_check ${i + 1} fail; return 1; fi`);
    });
    L.push("  return 0");
  } else {
    L.push('  sayops_err "this plan has no verification checks, so recovery cannot be verified"', "  return 1");
  }
  L.push(
    "}",
    "",
    "sayops_fail_and_recover() {",
    "  sayops_rollback",
    '  if [ "$SAYOPS_ROLLBACK_OK" = 1 ] && sayops_verify_recovery; then',
    "    sayops_event recovery verified",
    '    sayops_err "recovery verified: the checks pass after rollback (the task itself did not complete)"',
    "    exit 5",
    "  fi",
    "  sayops_event recovery unverified",
    '  sayops_err "RECOVERY NOT VERIFIED: check the system by hand before retrying"',
    "  exit 4",
    "}",
    "",
    "sayops_fail() {",
    '  sayops_event step_fail "$1" "${3:-1}"',
    '  case "$2" in',
    '    continue) sayops_err "$1 failed (exit ${3:-1}); continuing as planned" ;;',
    '    abort) sayops_err "$1 failed (exit ${3:-1}); stopping. This step has no rollback, so the system was not checked"; sayops_event stopped; exit 1 ;;',
    '    *) sayops_err "$1 failed (exit ${3:-1})"; sayops_fail_and_recover ;;',
    "  esac",
    "}",
    "",
    `sayops_log ${shq(`${oneLine(plan.title)} — run`)}" $SAYOPS_RUN_ID"`,
  );
  // Approve every HIGH-risk step before anything runs, so a refusal never leaves a half-done change.
  const high = plan.steps.filter((s) => s.risk === "HIGH");
  if (high.length) {
    L.push("", "# ── Approvals: every HIGH-risk step is approved up front, before any change is made");
    for (const s of high) L.push(`sayops_confirm ${s.id} ${shq(oneLine(s.run, 100))}`);
  }

  // ---- steps ----------------------------------------------------------------
  for (const step of plan.steps) L.push("", ...renderStep(step, quote, why, exec));

  // ---- verification -----------------------------------------------------------
  if (plan.verify.length) {
    L.push("", "# ── Verify");
    plan.verify.forEach((v: PlanCheck, i) => {
      L.push(`# ${why([v.why])}`);
      L.push(`sayops_log ${shq(`verify ${i + 1}: ${oneLine(v.run, 80)}`)}`);
      L.push(`if ${exec(v.remote, v.run)}; then sayops_event verify ${i + 1} ok; else sayops_event verify ${i + 1} fail; sayops_err ${shq(`verification ${i + 1} failed`)}; sayops_fail_and_recover; fi`);
    });
  }
  L.push("", "sayops_event finished", `sayops_log ${shq(`done: ${oneLine(plan.title)}`)}`, "");
  return L.join("\n");
}

function renderStep(
  step: PlanStep,
  quote: (id: string) => string,
  why: (ids: string[]) => string,
  exec: (remote: boolean, cmd: string) => string,
): string[] {
  const L: string[] = [];
  const tags = [step.added ? "ADDED BY SAYOPS — review" : "", step.risk !== "LOW" ? `${step.risk} risk` : ""].filter(Boolean);
  L.push(`# ── ${step.id} · ${oneLine(step.intent, 90)}${tags.length ? ` [${tags.join(", ")}]` : ""}`);
  if (step.sources.length) L.push(`#    from ${why(step.sources)}`);
  L.push(`sayops_log ${shq(`${step.id} · ${oneLine(step.intent, 90)}`)}`);

  const run = [
    `sayops_event step_start ${step.id}`,
    `if ${exec(step.remote, step.run)}; then sayops_event step_ok ${step.id}; sayops_log ${shq(`${step.id} ok`)}; else sayops_fail ${step.id} ${step.on_fail} "$?"; fi`,
  ];
  const c = step.condition;
  if (!c) return [...L, ...run];
  L.push(`#    skip ${c.scope === "all" ? "the whole task" : "this step"} when: ${quote(c.why)}`);
  if (c.scope === "all") {
    return [
      ...L,
      `if sayops_check ${exec(c.remote, c.skip_if).replace(/^sayops_exec /, "")}; then`,
      `  sayops_event skip all ${step.id}`,
      `  sayops_log ${shq(`nothing to do: condition from ${c.why} is met`)}`,
      "  exit 0",
      "fi",
      ...run,
    ];
  }
  return [
    ...L,
    `if sayops_check ${exec(c.remote, c.skip_if).replace(/^sayops_exec /, "")}; then`,
    `  sayops_event skip step ${step.id}`,
    `  sayops_log ${shq(`${step.id} skipped: condition from ${c.why} is met`)}`,
    "else",
    ...run.map((l) => `  ${l}`),
    "fi",
  ];
}
