import type { Plan, PlanStep } from "../schemas";
import type { RenderContext } from "./context";
import { isSecretParam, slugify } from "./shell";

const ON_FAIL: Record<PlanStep["on_fail"], string> = {
  continue: "Log it and continue.",
  abort: "Stop. Nothing is rolled back.",
  abort_and_rollback: "Stop and run the rollback below.",
};

const md = (s: string) => s.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
const fence = (cmd: string) => ["```bash", cmd, "```"].join("\n");

/** Human runbook: what, why (in the engineer's own words), how to check, how to undo. */
export function renderRunbook(plan: Plan, ctx: RenderContext): string {
  const said = (id: string) => (ctx.sources[id] && id.startsWith("N") ? `> “${md(ctx.sources[id])}” — ${id}` : "");
  const cite = (ids: string[]) => ids.map((id) => `\`${id}\``).join(" ");
  const L: string[] = [];

  L.push(
    `# Runbook: ${plan.title}`,
    "",
    `Generated by SayOps from recorded session \`${ctx.sessionId}\` (plan v${ctx.version}). Every step cites where it came from:`,
    "`C<n>` is a command that was run, `N<n>` is something the engineer said, `X<n>` is a later correction.",
    "",
    `Automated version: \`scripts/sayops/${slugify(plan.title)}.sh\` (run with \`--dry-run\` first).`,
    "",
    "## Parameters",
    "",
    "| Name | Recorded value | Source | How to supply |",
    "| --- | --- | --- | --- |",
    ...plan.params.map((p) => `| \`${p.name}\` | ${isSecretParam(p.from) ? "_redacted secret_" : `\`${md(p.from)}\``} | \`${p.why}\` | ${isSecretParam(p.from) ? "environment only" : `\`--${p.name.toLowerCase().replace(/_/g, "-")}\` or env`} |`),
    "",
  );

  const findings = plan.findings;
  if (findings.length) {
    L.push("## Review first", "");
    for (const f of findings) {
      const fix = f.fix_step ? ` SayOps added step **${f.fix_step}** for it — confirm it is right.` : " **Not fixed automatically — resolve before running.**";
      L.push(`- **${f.type.replace(/_/g, " ")}** (${cite(f.sources)}): ${md(f.detail)}${fix}`);
    }
    L.push("");
  }

  L.push("## Steps", "");
  for (const s of plan.steps) {
    const flags = [s.added ? "added by SayOps" : "", `${s.risk.toLowerCase()} risk`, s.remote ? `on \`$${plan.remote_host}\`` : "local"].filter(Boolean);
    L.push(`### ${s.id}. ${s.intent}`, "", `_${flags.join(" · ")} · sources ${cite(s.sources) || "none"}_`, "");
    const quotes = s.sources.map(said).filter(Boolean);
    if (quotes.length) L.push(...quotes, "");
    if (s.condition) {
      L.push(`**Skip ${s.condition.scope === "all" ? "the whole task" : "this step"} if this succeeds** (${cite([s.condition.why])}):`, "", fence(s.condition.skip_if), "");
    }
    L.push(fence(s.run), "", `**If it fails:** ${ON_FAIL[s.on_fail]}`, "");
    if (s.risk === "HIGH") L.push("**Approval required:** the script asks for confirmation; the workflow runs in the `sayops-approval` environment.", "");
  }

  L.push("## Rollback", "");
  if (plan.rollback.length) {
    plan.rollback.forEach((r, i) => L.push(`${i + 1}. ${said(r.why) ? `${md(ctx.sources[r.why])} (${cite([r.why])})` : cite([r.why])}`, "", fence(r.run), ""));
    L.push(
      "`sayops_restore <path>` moves the current state aside to `<path>.sayops-failed.<run>` (kept for inspection, never deleted)",
      "and copies the backup made by `sayops_backup <path>` back into place. The backup stays intact, so a restore can be repeated.",
      "",
    );
  } else {
    L.push("_No rollback was described. Check the system by hand if a step fails._", "");
  }

  L.push("## Verify", "");
  if (plan.verify.length) plan.verify.forEach((v) => L.push(fence(v.run), "", `From ${cite([v.why])}. A failure here triggers the rollback.`, ""));
  else L.push("_No verification was described._", "");
  return L.join("\n");
}
