import type { Plan } from "../schemas";
import type { RenderContext } from "./context";
import { isSecretParam, oneLine, slugify } from "./shell";

/** YAML double-quoted scalar (JSON strings are valid YAML). */
const y = (s: string) => JSON.stringify(s);

/**
 * GitHub Actions workflow that runs the rendered script. Every `${{ }}` value reaches the
 * script through `env:` — never interpolated into `run:` — so inputs cannot inject shell.
 * HIGH-risk plans run in an environment meant to have required reviewers.
 */
export function renderWorkflow(plan: Plan, ctx: RenderContext): string {
  const slug = slugify(plan.title);
  const high = plan.steps.some((s) => s.risk === "HIGH");
  const remote = Boolean(plan.remote_host) && plan.steps.some((s) => s.remote || s.condition?.remote) ;
  const inputs = plan.params.filter((p) => !isSecretParam(p.from));
  const secrets = plan.params.filter((p) => isSecretParam(p.from));
  const input = (name: string) => name.toLowerCase();
  const L: string[] = [];

  L.push(
    `# Generated by SayOps from session ${ctx.sessionId}, plan v${ctx.version}. Review before merging.`,
    `# Expects the script at scripts/sayops/${slug}.sh.`,
    `# Scheduled runs read parameters from repository variables (${inputs.map((p) => `SAYOPS_${p.name}`).join(", ") || "none"}).`,
    `name: ${y(`SayOps: ${oneLine(plan.title, 80)}`)}`,
    "",
    "on:",
    "  workflow_dispatch:",
  );
  if (inputs.length) {
    L.push("    inputs:");
    for (const p of inputs) {
      L.push(
        `      ${input(p.name)}:`,
        `        description: ${y(`${p.name} (recorded as ${p.from})`)}`,
        "        required: false",
        "        type: string",
      );
    }
  }
  if (plan.schedule) {
    const said = ctx.sources[plan.schedule.why];
    L.push(
      `  # From ${plan.schedule.why}${said ? `: "${oneLine(said, 90).replace(/"/g, "'")}"` : ""} (GitHub runs cron in UTC)`,
      "  schedule:",
      `    - cron: ${y(plan.schedule.cron)}`,
      "",
    );
  } else {
    L.push(
      "  # Add a schedule after a manual run has passed, e.g.:",
      "  # schedule:",
      '  #   - cron: "0 9 * * 1"',
      "",
    );
  }
  L.push(
    "permissions:",
    "  contents: read",
    "",
    "concurrency:",
    `  group: ${y(`sayops-${slug}`)}`,
    "  cancel-in-progress: false",
    "",
    "jobs:",
    "  run:",
    `    name: ${y(oneLine(plan.title, 80))}`,
    "    runs-on: ubuntu-latest",
    "    timeout-minutes: 30",
  );
  if (high) L.push("    # HIGH-risk steps: configure required reviewers on this environment.", "    environment: sayops-approval");
  L.push("    steps:", "      - name: Check out", "        uses: actions/checkout@v4");
  if (remote) {
    L.push(
      "      - name: Configure SSH",
      "        env:",
      "          SSH_PRIVATE_KEY: ${{ secrets.SAYOPS_SSH_PRIVATE_KEY }}",
      "          SSH_KNOWN_HOSTS: ${{ secrets.SAYOPS_SSH_KNOWN_HOSTS }}",
      "        run: |",
      "          install -m 700 -d ~/.ssh",
      "          printf '%s\\n' \"$SSH_PRIVATE_KEY\" > ~/.ssh/id_sayops",
      "          chmod 600 ~/.ssh/id_sayops",
      "          printf '%s\\n' \"$SSH_KNOWN_HOSTS\" > ~/.ssh/known_hosts",
      "          printf 'Host *\\n  IdentityFile ~/.ssh/id_sayops\\n  IdentitiesOnly yes\\n' > ~/.ssh/config",
    );
  }
  L.push(`      - name: ${y(`Run ${slug}.sh`)}`, "        env:");
  for (const p of inputs) L.push(`          ${p.name}: \${{ inputs.${input(p.name)} || vars.SAYOPS_${p.name} }}`);
  for (const p of secrets) L.push(`          ${p.name}: \${{ secrets.${p.name} }}`);
  L.push("          SAYOPS_RUN_ID: ${{ github.run_id }}-${{ github.run_attempt }}");
  if (high) L.push('          SAYOPS_APPROVED: "1" # approval happens through the environment\'s required reviewers');
  L.push(`        run: bash scripts/sayops/${slug}.sh`, "");
  return L.join("\n");
}
