/**
 * Records real "Say it yourself" examples for the SSL demo: each is one live compile with one spoken
 * reason added to one command. The public page shows them as recorded results (instant, no AI call).
 *   npm run reasons:seed -w @sayops/core     (needs GROQ_API_KEY in sayops/.env; free tier is fine)
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { explainStep, formatDiff, groq, sourceTexts, sslRenewEvents, sslRenewMeta, sslRenewPlan } from "../src";

for (const f of ["../../../.env", "../../../web/.env.local"]) {
  try { process.loadEnvFile(fileURLToPath(new URL(f, import.meta.url))); } catch { /* optional */ }
}
const apiKey = process.env.GROQ_API_KEY;
if (!apiKey) { console.error("GROQ_API_KEY is not set"); process.exit(1); }
const llm = groq({ apiKey, model: process.env.LLM_MODEL || undefined });

const asks = [
  { commandSeq: 3, text: "Never stop nginx if the disk is over 90% full, or the renewal can fail halfway." },
  { commandSeq: 4, text: "Before renewing, make sure nothing else is using port 80, otherwise certbot will fail." },
  { commandSeq: 7, text: "If the site doesn't answer within 10 seconds, the check should fail instead of hanging." },
];

const out = [];
for (const [i, a] of asks.entries()) {
  if (i) await new Promise((r) => setTimeout(r, 65_000)); // free tier: tokens per minute
  const r = await explainStep({ llm, title: sslRenewMeta.title, events: sslRenewEvents, plan: sslRenewPlan, ...a });
  console.log(`\nC${a.commandSeq} N${r.narration.seq} (${r.kind}) "${a.text}"`);
  for (const l of formatDiff(r.diff, sourceTexts(r.session))) console.log(l);
  out.push({ ...a, narrationSeq: r.narration.seq, kind: r.kind, model: r.model, recordedAt: new Date().toISOString(), plan: r.plan });
}

const file = fileURLToPath(new URL("../src/seeds/ssl-renew.reasons.ts", import.meta.url));
writeFileSync(
  file,
  `// Generated by scripts/reason-seed.ts from real compiles. Do not edit by hand; re-run: npm run reasons:seed -w @sayops/core\n` +
    `import type { NarrationKind, Plan } from "../schemas";\n\n` +
    `export interface ReasonExample { commandSeq: number; text: string; narrationSeq: number; kind: NarrationKind | null; model: string; recordedAt: string; plan: Plan }\n\n` +
    `export const sslRenewReasons: ReasonExample[] = ${JSON.stringify(out, null, 2)};\n`,
);
console.log(`\nwrote ${file}`);
