/**
 * Records a real talk-to-fix example for the SSL demo: one live compile with a spoken correction,
 * starting from the seed plan. The website shows this as a recorded example (it never calls the AI).
 *   npm run correction:seed -w @sayops/core     (needs GROQ_API_KEY in sayops/.env)
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { align, compile, diffPlans, formatDiff, groq, redactEvents, redactText, sourceTexts, sslRenewEvents, sslRenewMeta, sslRenewPlan } from "../src";

for (const f of ["../../../.env", "../../../web/.env.local"]) {
  try { process.loadEnvFile(fileURLToPath(new URL(f, import.meta.url))); } catch { /* optional */ }
}
const apiKey = process.env.GROQ_API_KEY;
if (!apiKey) { console.error("GROQ_API_KEY is not set"); process.exit(1); }

const spoken = "Also post to Slack when it's done, and run this every Monday at 9.";
const correction = { seq: 1, text: redactText(spoken).text };
const session = align(redactEvents(sslRenewEvents).events);
const r = await compile(groq({ apiKey, model: process.env.LLM_MODEL || undefined }), { title: sslRenewMeta.title, session, corrections: [correction], previous: sslRenewPlan });
const diff = diffPlans(sslRenewPlan, r.plan);
console.log(`${r.model} · ${r.attempts} attempt(s)`);
for (const l of formatDiff(diff, sourceTexts(session, [correction]))) console.log(l);

const out = fileURLToPath(new URL("../src/seeds/ssl-renew.correction.ts", import.meta.url));
const example = { correction, recordedAt: new Date().toISOString(), model: r.model, attempts: r.attempts, plan: r.plan };
writeFileSync(
  out,
  `// Generated by scripts/correction-seed.ts from a real compile. Do not edit by hand; re-run: npm run correction:seed -w @sayops/core\n` +
    `import type { Plan } from "../schemas";\n\n` +
    `export interface CorrectionExample { correction: { seq: number; text: string }; recordedAt: string; model: string; attempts: number; plan: Plan }\n\n` +
    `export const sslRenewCorrection: CorrectionExample | null = ${JSON.stringify(example, null, 2)};\n`,
);
console.log(`wrote ${out}`);
