/**
 * Proves the SSL seed's generated script in the Docker sandbox and records the real results.
 *   npm run proof:ssl -w @sayops/core
 * Writes src/seeds/ssl-renew.proof.ts, which the session page displays. Needs Docker.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { align, redactEvents, renderScript, sourceTexts, sslRenewEvents, sslRenewPlan } from "../src";
import { runProof } from "../src/proof/runner";

const session = align(redactEvents(sslRenewEvents).events);
const script = renderScript(sslRenewPlan, { sessionId: "ssl-renew", version: 1, sources: sourceTexts(session) });
const sandboxDir = fileURLToPath(new URL("../../../sandbox/ssl", import.meta.url));

const run = runProof({ plan: sslRenewPlan, script, sessionId: "ssl-renew", sandboxDir });
for (const s of run.scenarios) {
  console.log(`\n${s.passed ? "PASS" : "FAIL"} ${s.id} — exit ${s.exitCode} (expected ${s.expectedExit}) in ${(s.durationMs / 1000).toFixed(1)}s`);
  for (const step of s.steps) console.log(`  ${step.status.padEnd(8)} ${step.id} ${step.command}`);
  if (s.rollback.ran) console.log(`  rollback: ${s.rollback.commands.map((c) => `${c.index}:${c.ok ? "ok" : "fail"}`).join(" ")} · recovery ${s.recovery}`);
  for (const c of s.checks) console.log(`  ${c.ok ? "✔" : "✖"} ${c.label} (expected ${c.expected}, got ${c.actual})`);
}
const out = fileURLToPath(new URL("../src/seeds/ssl-renew.proof.ts", import.meta.url));
writeFileSync(
  out,
  `// Generated by scripts/proof-ssl.ts from a real sandbox run. Do not edit by hand; re-run: npm run proof:ssl -w @sayops/core\n` +
    `import type { ProofRun } from "../proof";\n\nexport const sslRenewProof: ProofRun | null = ${JSON.stringify(run, null, 2)};\n`,
);
console.log(`\nwrote ${out}`);
process.exit(run.scenarios.every((s) => s.passed) ? 0 : 1);
